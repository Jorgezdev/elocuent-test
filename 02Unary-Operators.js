// algunos operadores en javascript no son simbolos, sino que palabras como typeof, delete, void, etc. Estos se llaman operadores unarios porque solo operan sobre un operando.

// operador typeof devuelve el tipo de dato de una variable o valor
let numero = 42;
console.log(typeof numero); // "number"

let palabra = "Hola";
console.log(typeof palabra); // "string"    

//los operadores que necesitan 2 valores para funcionar se llaman operadores binarios, como +, -, *, / 
//en cambio los operadores unarios solo necesitan un valor para funcionar, como typeof, delete, void, etc.

